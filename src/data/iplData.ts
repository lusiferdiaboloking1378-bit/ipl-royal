export function getFranchiseById(id: string): Franchise {
  return IPL_FRANCHISES.find((f) => f.id === id) || IPL_FRANCHISES[0];
}

export function normalizeStatForBar(stat: StatKey, value: number): number {
  const meta = STAT_META[stat];
  const clamped = Math.max(meta.min, Math.min(meta.max, value));
  const ratio = (clamped - meta.min) / (meta.max - meta.min);
  const score = meta.higherIsBetter ? ratio : 1 - ratio;
  return Math.round(Math.max(0.08, Math.min(1, score)) * 100);
}
